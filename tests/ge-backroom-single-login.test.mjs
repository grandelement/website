import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=path=>readFileSync(path,'utf8');
const back=read('backroom/index.html');
const music=read('backroom/music-router.js');
const worker=read('backroom/publisher-worker.js');
assert.match(back,/id="gatePassword"/,'One existing Back Room password');
assert.match(back,/id="gateEnter"/,'One existing unlock button');
assert.match(back,/id="brTopSave"/,'One visible central SAVE');
assert.doesNotMatch(back,/id="brDirectPublisherFrame"/,'No device-token iframe');
assert.doesNotMatch(back,/github-bridge\.js/,'No second login bridge');
assert.match(back,/id="brCatalogRouting"/,'Radio music controls available');
assert.match(back,/id="brPublicPlayerProfile"/,'Public Player profile available');
assert.match(back,/id="brGithubConnection"/,'GitHub connectivity distinct from Vault');
assert.match(back,/api\('\/manage\/public-config'/,'Load main branch from server on login');
assert.match(back,/api\('\/manage\/github-health'/,'Check server GitHub login health');
assert.match(back,/api\('\/manage\/public-settings'/,'Public changes saved through Worker');
assert.match(music,/ownerApi\('POST',\{action:'save_catalog_routing'/,'Music save uses Worker');
assert.match(music,/const proof=await ownerApi\('GET'\)/,'Music save requires GitHub readback');
assert.doesNotMatch(music,/oldProfile\.parentElement\.insertBefore/,'Website player remains under Website');
assert.match(worker,/url\.pathname==='\/manage\/github-health'/);
assert.match(worker,/url\.pathname==='\/manage\/public-config'/);
assert.match(worker,/if\(env\.GITHUB_TOKEN\)return String\(env\.GITHUB_TOKEN\)/);
console.log('PASS: one entrance, one server GitHub publisher, authoritative startup load, verified music/website SAVE; no device-token editor.');
